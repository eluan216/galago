export function isDashboardLocale(value: unknown): value is DashboardLocale {
  return (
    typeof value === "string" &&
    dashboardLocales.includes(value as DashboardLocale)
  );
}

export function translate(locale: DashboardLocale, source: string): string {
  if (locale === "en") return source;
  return translations[locale]?.[source] || source;
}
